#!/usr/bin/env python3
"""Rebuild assets/themes.json: the per-variant data the SVG output needs (fitted template colours,
emboss colours, front-panel centre), measured from the PNG folders of every Yaru* theme found.

Usage: build_themes_json.py [--icons-root /usr/share/icons] [--out assets/themes.json]
Run it again when a new Yaru release adds or changes a variant (the tests tell you when).
"""
import argparse, json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def load_script():
    sys.path.insert(0, ROOT)
    from folder_symbols import yaru
    return yaru


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--icons-root", default="/usr/share/icons")
    p.add_argument("--out", default=os.path.join(ROOT, "assets", "themes.json"))
    a = p.parse_args()
    y = load_script()
    names = sorted(d for d in os.listdir(a.icons_root) if d.startswith("Yaru")
                   and os.path.isdir(os.path.join(a.icons_root, d, y.SIZE_DIRS[-1], "places")))
    if not names:
        sys.exit(f"no Yaru themes with PNG folders in {a.icons_root}")
    themes = {}
    for n in names:
        themes[n] = y.compute_svg_data(os.path.join(a.icons_root, n))
        print(f"{n:24s} {themes[n]['colors']} d1={themes[n]['d1']} d2={themes[n]['d2']} centre={themes[n]['center']}")
    doc = {"_comment": "Generated by tools/build_themes_json.py from the PNG folders of the Yaru icon "
                       "themes. Do not edit by hand.", "format": 1, "themes": themes}
    with open(a.out, "w", encoding="utf-8") as f:
        json.dump(doc, f, indent=1, sort_keys=False)
        f.write("\n")
    print(f"{len(themes)} themes -> {a.out}")


if __name__ == "__main__":
    main()
